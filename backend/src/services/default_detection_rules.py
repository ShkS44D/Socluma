from __future__ import annotations

from typing import Any

from src.models.sqlalchemy import EventType, RuleType, Severity


def _sigma(
    title: str,
    description: str,
    event_type: EventType,
    severity: Severity,
    detection: dict[str, Any],
    mitre: str,
    false_positives: list[str],
    recommendations: list[str],
    confidence: int = 75,
    references: list[str] | None = None,
) -> dict[str, Any]:
    rule_content = {
        "title": title,
        "description": description,
        "status": "stable",
        "logsource": {
            "category": "process_creation" if event_type == EventType.PROCESS else event_type.value,
        },
        "detection": detection,
        "fields": ["Image", "CommandLine", "ParentImage", "User", "EventID"],
        "falsepositives": false_positives,
        "tags": [f"attack.{mitre.lower()}"],
        "references": references or ["https://attack.mitre.org/"],
        "level": severity.value,
        "triage": {
            "recommendations": recommendations,
            "confidence": confidence,
        },
    }
    return {
        "name": title,
        "description": description,
        "type": RuleType.SIGMA,
        "rule_type": RuleType.SIGMA,
        "event_type": event_type,
        "severity": severity,
        "enabled": True,
        "condition": None,
        "rule_content": rule_content,
        "query": "",
        "sigma_rule": "",
        "mitre_technique_id": mitre,
    }


